"""Comparison persistence, CSV export, and ImageJ/Fiji macro generation."""
import csv
import json
from pathlib import Path
import numpy as np

SCHEMA = 'loupe.comparison.v1'

def write_csv(path, profiles):
    """Export native TIFF line or rectangle mean profiles, one record per sample.

    The CSV layout remains compatible with LOUPE Day 3. Coordinates refer to
    pixel-center positions, the *mean* column contains unmodified TIFF values.
    """
    with open(path, 'w', encoding='utf-8-sig', newline='') as f:
        w=csv.writer(f)
        w.writerow(['panel','source_tiff','slice_1_based','width_px','method','sample_index','distance_px','x_px','y_px','mean_intensity'])
        for panel in profiles:
            distance,values=panel['profile']
            n=len(distance)
            if 'coords' in panel:
                xs,ys=panel['coords']
            else:
                start,end=panel['line']
                xs=np.linspace(start[0],end[0],n)
                ys=np.linspace(start[1],end[1],n)
            if len(xs)!=n or len(ys)!=n:
                raise ValueError('Profile coordinates and data have different lengths')
            kind=panel.get('kind','mean')
            for i,(d,v,x,y) in enumerate(zip(distance,values,xs,ys)):
                w.writerow([panel['side'],str(panel['path']),panel['slice'],panel['width'],kind,i,
                            f'{float(d):.12g}',f'{float(x):.12g}',f'{float(y):.12g}',
                            f'{float(v):.12g}' if np.isfinite(v) else ''])

def write_session(path, state):
    obj={'schema':SCHEMA,'settings':state['settings'],'panels':state['panels']}
    Path(path).write_text(json.dumps(obj,indent=2,ensure_ascii=False,allow_nan=False),encoding='utf-8')

def read_session(path):
    obj=json.loads(Path(path).read_text(encoding='utf-8'))
    if (obj.get('schema') != SCHEMA or not isinstance(obj.get('settings'),dict) or
            not isinstance(obj.get('panels'),list) or not (1 <= len(obj['panels']) <= 4) or
            not all(isinstance(p, dict) for p in obj['panels'])):
        raise ValueError('Not a LOUPE comparison v1 JSON (requires 1–4 panels)')
    return obj

def imagej_escape(path):
    # ImageJ macro strings cannot contain unescaped double quotes/backslashes.
    return str(path).replace(chr(92), "/").replace(chr(34), chr(92)+chr(34))

def imagej_macro(state):
    """Open 1–4 visible slices and approximate equivalent straight thick-line mean profiles.
    Reproducibility limitation: ImageJ's native profile interpolation/edge behavior
    may differ from LOUPE's bilinear perpendicular strip mean; verify numerically.
    """
    s=state['settings']; lines=[
        '// Generated by LOUPE. ImageJ/Fiji macro language.',
        '// Profile values may differ: native ImageJ interpolation / thick-line sampling.',
        '// Requires ImageJ/Fiji with straight-line ROI and Plot Profile support.',
        'setBatchMode(false);',
        '// Existing ImageJ images are left open.'
    ]
    width=int(s['width_px'])
    for panel in state['panels']:
        if not panel.get('path'): continue
        name=panel['side']; low,hi=panel['levels']
        lines += [
            f'open("{imagej_escape(panel["path"])}");',
            f'rename("LOUPE {name}");',
            f'setMinAndMax({low:.12g}, {hi:.12g});',
        ]
        if s.get('profile_source', 'line') != 'line':
            lines += ['// Rectangle mean profile: not automatically reproduced by this ImageJ macro.',
                      '// Use LOUPE Export CSV for native rectangle-mean values.']
        elif panel.get('line') is not None:
            a,b=panel['line']
            lines += [
                f'makeLine({int(round(a[0]))}, {int(round(a[1]))}, {int(round(b[0]))}, {int(round(b[1]))});',
                f'setLineWidth({width});',
                'run("Plot Profile");',
            ]
    lines += ['// LOUPE session JSON is the authoritative record for zoom/pan and exact sampling.', '']
    return '\n'.join(lines)
